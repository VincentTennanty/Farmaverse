#' Demo Dairy Herd Dataset
#'
#' A synthetic dairy herd of 200 cows with milk production data, generated
#' using the full VirtualDairyHerdR simulation pipeline. Suitable for
#' general exploration, visualisation, and regression exercises.
#'
#' @format A tibble with 200 rows and 11 columns:
#' \describe{
#'   \item{cow_id}{Character. Unique cow identifier (e.g. "COW0001").}
#'   \item{breed}{Character. Breed — Holstein, Friesian, Jersey, or Crossbred.}
#'   \item{age}{Integer. Age in years.}
#'   \item{lactation}{Integer. Lactation number (parity), 1–6.}
#'   \item{days_in_milk}{Integer. Days in milk at snapshot date, 1–305.}
#'   \item{milk_kg}{Numeric. Daily milk yield in kg.}
#'   \item{fat_percent}{Numeric. Milk fat percentage.}
#'   \item{protein_percent}{Numeric. Milk protein percentage.}
#'   \item{scc}{Integer. Somatic cell count (cells/mL).}
#'   \item{synthetic_data}{Logical. Always TRUE — flags this as synthetic data.}
#'   \item{source}{Character. Always "VirtualDairyHerdR".}
#' }
#'
#' @details
#' Generated with:
#' ```r
#' farm      <- simulate_farm(name = "Greenfield Farm", n_cows = 200, seed = 42)
#' herd      <- simulate_herd(farm = farm)
#' demo_herd <- simulate_milk(herd, seed = 42)
#' ```
#'
#' @source Generated by VirtualDairyHerdR. See `data-raw/generate_demo_data.R`.
#'
#' @examples
#' data(demo_herd)
#' head(demo_herd)
#' education_summary(demo_herd, by = "breed")
"demo_herd"


#' Demo Mastitis Dataset
#'
#' A synthetic dairy herd of 200 cows with mastitis labels applied at 15%
#' prevalence. Built on top of [demo_herd] with mastitis disease effects
#' applied. Suitable for binary classification exercises.
#'
#' @format A tibble with 200 rows and 14 columns. All columns from [demo_herd]
#' plus:
#' \describe{
#'   \item{temperature}{Numeric. Body temperature in °C. Elevated in mastitis cases.}
#'   \item{rumination_minutes}{Integer. Daily rumination time in minutes. Reduced in mastitis cases.}
#'   \item{mastitis}{Logical. TRUE if the cow has mastitis. The classification target.}
#' }
#'
#' @details
#' Mastitis cases (approx. 15% of cows) have:
#' - Milk yield reduced by 15–40%
#' - SCC elevated 5–20x
#' - Body temperature increased +0.5 to +2.5 °C
#' - Rumination reduced by 20–50%
#'
#' Generated with:
#' ```r
#' demo_mastitis <- simulate_mastitis(demo_herd, prevalence = 0.15, seed = 42)
#' ```
#'
#' @source Generated by VirtualDairyHerdR. See `data-raw/generate_demo_data.R`.
#'
#' @examples
#' data(demo_mastitis)
#' table(demo_mastitis$mastitis)
#' education_summary(demo_mastitis, by = "breed")
"demo_mastitis"
